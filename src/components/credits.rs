#[cfg(feature = "credits")]
mod catalog {
    use std::collections::HashMap;
    use std::sync::LazyLock;

    use serde::Deserialize;

    /// A third party library along with the license and its version
    #[derive(Deserialize)]
    pub struct CrateCredit {
        pub name: String,
        pub version: String,
        pub license: String,
    }

    /// The verbatim license content for a given SPDX ID, along with the libraries that use it
    #[derive(Deserialize)]
    pub struct LicenseText {
        pub id: String,
        pub text: String,
        pub crates: Vec<String>,
    }

    #[derive(Deserialize)]
    pub struct Catalog {
        pub crates: Vec<CrateCredit>,
        pub licenses: Vec<LicenseText>,
    }

    /// License catalog generated by build.rs
    pub static CATALOG: LazyLock<Catalog> = LazyLock::new(|| {
        serde_json::from_str(include_str!(concat!(env!("OUT_DIR"), "/credits.json")))
            .expect("failed to deserialize credits JSON")
    });

    /// A mapping of `{name} {version}` to a license's index in [`CATALOG`]. `OR` obligations
    /// only pick one, while `AND` obligations display both
    static CRATE_LICENSES: LazyLock<HashMap<&'static str, Vec<usize>>> = LazyLock::new(|| {
        let mut map: HashMap<&'static str, Vec<usize>> = HashMap::new();
        for (i, lic) in CATALOG.licenses.iter().enumerate() {
            for key in &lic.crates {
                let entry = map.entry(key.as_str()).or_default();
                if !entry.iter().any(|&j| CATALOG.licenses[j].id == lic.id) {
                    // deduplicate license, same license may heva different text variants
                    entry.push(i);
                }
            }
        }
        map
    });

    /// Given an SPDX ID for a license, returns its index in the [`CATALOG`] to query for
    /// its verbatim text
    pub fn resolved(key: &str) -> &'static [usize] {
        CRATE_LICENSES.get(key).map_or(&[][..], Vec::as_slice)
    }
}

const MAGENTA: Color = Color::Magenta;
const DIM: Color = Color::DarkGray;
const BODY: Color = Color::White;

#[derive(Default)]
pub struct Credits {
    visible: bool,
    selected: usize,
    detail: bool,
    scroll: u16,
}

impl Credits {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn is_visible(&self) -> bool {
        self.visible
    }

    fn open(&mut self) {
        self.visible = true;
        self.detail = false;
        self.scroll = 0;
    }

    pub(super) fn crate_count() -> usize {
        cfg_if! {
            if #[cfg(feature = "credits")] {
                catalog::CATALOG.crates.len()
            } else {
                0
            }
        }
    }

    fn total() -> usize {
        ASSETS.len() + Self::crate_count()
    }

    /// Handles a [`KeyEvent`] while the overlay view is active, returning whether it
    /// consumed the input, or whether it needs to be handled elsewhere
    pub fn handle_key(&mut self, key: KeyEvent) -> bool {
        if self.detail {
            match key.code {
                KeyCode::Up => self.scroll = self.scroll.saturating_sub(1),
                KeyCode::Down => self.scroll = self.scroll.saturating_add(1),
                KeyCode::Esc | KeyCode::Left => {
                    self.detail = false;
                    self.scroll = 0;
                }
                _ => return false,
            }
        } else {
            match key.code {
                KeyCode::Up => self.selected = self.selected.saturating_sub(1),
                KeyCode::Down => {
                    self.selected = (self.selected + 1).min(Self::total().saturating_sub(1));
                }
                KeyCode::Enter | KeyCode::Right => {
                    self.detail = true;
                    self.scroll = 0;
                }
                KeyCode::Esc => self.visible = false,
                _ => return false,
            }
        }
        true
    }

    fn detail_lines(&self) -> Vec<Line<'static>> {
        let dim = Style::default().fg(DIM);
        let body = Style::default().fg(BODY);

        if self.selected < ASSETS.len() {
            let asset = &ASSETS[self.selected];
            let mut lines = vec![
                Line::styled(asset.name, Style::default().fg(MAGENTA).bold()),
                Line::styled(format!("{} · {}", asset.source, asset.license), dim),
                Line::default(),
            ];

            lines.extend(asset.text.lines().map(|l| Line::styled(l.to_string(), body)));
            return lines;
        }

        cfg_if! {
            if #[cfg(feature = "credits")] {
                let krate = &catalog::CATALOG.crates[self.selected - ASSETS.len()];
                let key = format!("{} {}", krate.name, krate.version);
                let mut lines = vec![Line::styled(
                    format!("{} {}", krate.name, krate.version),
                    Style::default().fg(MAGENTA).bold(),
                )];

                if krate.license.contains(" OR ") || krate.license.contains(" AND ") {
                    lines.push(Line::styled(format!("offered under {}", krate.license), dim));
                }

                lines.push(Line::default());

                let resolved = catalog::resolved(&key);
                if resolved.is_empty() {
                    lines.push(Line::styled(
                        format!("{} - no bundled license text", krate.license),
                        dim,
                    ));
                }

                for &i in resolved {
                    let license = &catalog::CATALOG.licenses[i];
                    lines.push(Line::styled(format!("── {} ──", license.id), dim));
                    lines.extend(license.text.lines().map(|l| Line::styled(l.to_string(), body)));
                    lines.push(Line::default());
                }

                lines
            } else {
                Vec::new()
            }
        }
    }

    fn list_lines(&self) -> (Vec<Line<'static>>, Option<usize>) {
        fn row(selected: bool, name: String, meta: String) -> Line<'static> {
            let dim = Style::default().fg(DIM);
            let name_style = if selected {
                Style::default().fg(BODY).bold()
            } else {
                Style::default().fg(BODY)
            };

            Line::from(vec![
                Span::styled(if selected { "› " } else { "  " }, Style::default().fg(MAGENTA)),
                Span::styled(name, name_style),
                Span::styled(meta, dim),
            ])
        }

        let head = Style::default().fg(MAGENTA).bold();
        let mut lines = Vec::new();
        let mut selected_line = None;

        lines.push(Line::styled("data & assets", head));

        for (i, asset) in ASSETS.iter().enumerate() {
            if i == self.selected {
                selected_line = Some(lines.len());
            }

            lines.push(row(
                i == self.selected,
                asset.name.to_string(),
                format!("  {} · {}", asset.source, asset.license),
            ));
        }

        #[cfg(feature = "credits")]
        {
            lines.push(Line::default());
            lines.push(Line::styled(
                format!("crates ({})", catalog::CATALOG.crates.len()),
                head,
            ));

            for (i, krate) in catalog::CATALOG.crates.iter().enumerate() {
                let idx = ASSETS.len() + i;
                if idx == self.selected {
                    selected_line = Some(lines.len());
                }

                let resolved = catalog::resolved(&format!("{} {}", krate.name, krate.version));
                let license = if resolved.is_empty() {
                    krate.license.clone()
                } else {
                    resolved
                        .iter()
                        .map(|&j| catalog::CATALOG.licenses[j].id.as_str())
                        .collect::<Vec<_>>()
                        .join(", ")
                };

                lines.push(row(
                    idx == self.selected,
                    format!("{} {}", krate.name, krate.version),
                    format!("  {license}"),
                ));
            }
        }

        (lines, selected_line)
    }
}

impl Component for Credits {
    fn update(&mut self, action: Action) -> Result<Option<Action>> {
        match action {
            Action::Credits => self.open(),
            Action::Quit => self.visible = false,
            _ => {}
        }

        Ok(None)
    }

    fn draw(&mut self, frame: &mut Frame, area: Rect) -> Result<()> {
        if !self.visible {
            return Ok(());
        }

        let width = 74.min(area.width);
        let height = area.height.saturating_sub(4).max(3);
        let [area] =
            Layout::horizontal([Constraint::Length(width)]).flex(Flex::Center).areas(area);
        let [area] =
            Layout::vertical([Constraint::Length(height)]).flex(Flex::Center).areas(area);

        let title = if self.detail { " credits · license " } else { " credits " };
        let footer = if self.detail {
            " ↑↓ scroll · esc back "
        } else {
            " ↑↓ move · ⏎ open · esc close "
        };

        let block = Block::default()
            .borders(Borders::ALL)
            .border_type(BorderType::Rounded)
            .border_style(Style::default().fg(MAGENTA))
            .padding(Padding::horizontal(1))
            .title(Span::styled(title, Style::default().fg(MAGENTA).bold()))
            .title_bottom(Span::styled(footer, Style::default().fg(DIM)));

        let inner = block.inner(area);
        frame.render_widget(Clear, area);
        frame.render_widget(block, area);

        if self.detail {
            frame.render_widget(
                Paragraph::new(self.detail_lines())
                    .wrap(Wrap { trim: false })
                    .scroll((self.scroll, 0)),
                inner,
            );

            return Ok(());
        }

        let (lines, selected_line) = self.list_lines();
        let inner_height = inner.height as usize;
        let sel = selected_line.unwrap_or(0);
        let offset = sel
            .saturating_sub(inner_height / 2)
            .min(lines.len().saturating_sub(inner_height)) as u16;

        frame.render_widget(Paragraph::new(lines).scroll((offset, 0)), inner);
        Ok(())
    }
}
